#!/usr/bin/env python3
"""Render paper-quality figures from the PDP cost-model CSV files.

Inputs are generated by experiments/related_cost_plots.py.  This script keeps
only the schemes compared in paper/FoldAudit.tex and writes vector PDF/SVG plus
600 dpi PNG figures suitable for manuscript inclusion.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
from matplotlib.ticker import LogLocator, NullFormatter, ScalarFormatter
from matplotlib.transforms import ScaledTranslation


ROOT = Path("experiments/out")
OUT = ROOT / "paper_figures"
BAR_XTICK_SHIFT_PT = 8.0

SCHEME_ORDER = [
    "YuTC25",
    "ZhangTPDS23",
    "MiaoSCIS2026",
    "XuTIFS26",
    "FoldAudit (Ours)",
]

DISPLAY = {
    "YuTC25": "YuTC25",
    "ZhangTPDS23": "ZhangTPDS23",
    "MiaoSCIS2026": "MiaoSCIS2026",
    "XuTIFS26": "XuTIFS26",
    "FoldAudit (Ours)": "FoldAudit",
}

PALETTE = {
    "YuTC25": "#4C78A8",
    "ZhangTPDS23": "#F58518",
    "MiaoSCIS2026": "#B279A2",
    "XuTIFS26": "#54A24B",
    "FoldAudit (Ours)": "#111111",
}

HATCHES = {
    "YuTC25": "",
    "ZhangTPDS23": "//",
    "MiaoSCIS2026": "\\\\",
    "XuTIFS26": "..",
    "FoldAudit (Ours)": "xx",
}


def setup_style() -> None:
    sns.set_theme(style="whitegrid", context="paper")
    plt.rcParams.update(
        {
            "font.family": "serif",
            "font.serif": ["Times New Roman", "Times", "DejaVu Serif"],
            "font.size": 8.5,
            "axes.labelsize": 8.5,
            "axes.titlesize": 9.5,
            "xtick.labelsize": 7.5,
            "ytick.labelsize": 7.5,
            "legend.fontsize": 7.5,
            "axes.linewidth": 0.8,
            "grid.linewidth": 0.45,
            "lines.linewidth": 1.5,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "svg.fonttype": "none",
            "figure.dpi": 160,
            "savefig.dpi": 600,
            "savefig.bbox": "tight",
            "savefig.pad_inches": 0.02,
        }
    )


def load_csv(name: str) -> pd.DataFrame:
    path = ROOT / name
    if not path.exists():
        raise FileNotFoundError(f"missing {path}; run experiments/related_cost_plots.py first")
    df = pd.read_csv(path)
    if "scheme" in df.columns:
        df = df[df["scheme"].isin(SCHEME_ORDER)].copy()
        df["scheme"] = pd.Categorical(df["scheme"], categories=SCHEME_ORDER, ordered=True)
        df = df.sort_values("scheme")
    return df


def save_all(fig: plt.Figure, stem: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    fig.savefig(OUT / f"{stem}.pdf")
    plt.close(fig)


def format_log_axis(ax: plt.Axes) -> None:
    ax.set_yscale("log")
    ax.yaxis.set_major_locator(LogLocator(base=10))
    ax.yaxis.set_minor_locator(LogLocator(base=10, subs=(2, 3, 4, 5, 6, 7, 8, 9)))
    ax.yaxis.set_minor_formatter(NullFormatter())
    ax.grid(True, axis="y", which="major", color="#D4D4D4")
    ax.grid(True, axis="y", which="minor", color="#ECECEC", alpha=0.65)
    ax.grid(False, axis="x")
    sns.despine(ax=ax, top=True, right=True)


def apply_hatches(ax: plt.Axes, schemes: list[str]) -> None:
    for patch, scheme in zip(ax.patches, schemes):
        patch.set_hatch(HATCHES[str(scheme)])
        patch.set_edgecolor("#222222")
        patch.set_linewidth(0.55)


def shift_xticklabels_right(ax: plt.Axes, points: float = BAR_XTICK_SHIFT_PT) -> None:
    shift = ScaledTranslation(points / 72.0, 0.0, ax.figure.dpi_scale_trans)
    for label in ax.get_xticklabels():
        label.set_transform(label.get_transform() + shift)


def short_time(seconds: float) -> str:
    if seconds >= 3600:
        return f"{seconds / 3600:.1f}h"
    if seconds >= 1:
        return f"{seconds:.0f}s"
    return f"{seconds * 1000:.0f}ms"


def bar_figure(df: pd.DataFrame, stem: str, title: str, ylabel: str) -> None:
    data = df.copy()
    data["label"] = data["scheme"].map(DISPLAY)
    fig, ax = plt.subplots(figsize=(3.45, 2.35))
    colors = [PALETTE[str(s)] for s in data["scheme"]]
    ax.bar(data["label"], data["seconds"], color=colors, width=0.68)
    apply_hatches(ax, list(data["scheme"]))
    format_log_axis(ax)
    ax.set_title(title, pad=4)
    ax.set_ylabel(ylabel)
    ax.set_xlabel("")
    ax.tick_params(axis="x", rotation=24)
    for tick in ax.get_xticklabels():
        tick.set_ha("right")
    shift_xticklabels_right(ax)
    ymax = data["seconds"].max()
    ax.set_ylim(max(data["seconds"].min() / 2.5, 1e-3), ymax * 2.8)
    for patch, value in zip(ax.patches, data["seconds"]):
        ax.text(
            patch.get_x() + patch.get_width() / 2,
            value * 1.12,
            short_time(float(value)),
            ha="center",
            va="bottom",
            fontsize=6.7,
            rotation=0,
        )
    fig.tight_layout()
    save_all(fig, stem)


def line_figure(df: pd.DataFrame, x: str, stem: str, title: str, xlabel: str, ylabel: str) -> None:
    fig, ax = plt.subplots(figsize=(3.45, 2.35))
    for scheme in SCHEME_ORDER:
        part = df[df["scheme"] == scheme].sort_values(x)
        if part.empty:
            continue
        ax.plot(
            part[x],
            part["seconds"],
            marker="o",
            markersize=3.2,
            label=DISPLAY[scheme],
            color=PALETTE[scheme],
        )
    format_log_axis(ax)
    ax.set_title(title, pad=4)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.xaxis.set_major_formatter(ScalarFormatter())
    ax.legend(
        ncol=2,
        frameon=False,
        handlelength=1.5,
        columnspacing=0.9,
        loc="upper left",
    )
    fig.tight_layout()
    save_all(fig, stem)


def combined_panel(bar_data: dict[str, pd.DataFrame], line_data: dict[str, pd.DataFrame]) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(7.1, 4.45))
    panel_titles = [
        ("(a) Audit time", bar_data["audit"]),
        ("(b) Verification time", bar_data["verify"]),
        ("(c) Store/TagGen time", bar_data["store"]),
    ]
    for ax, (title, data) in zip(axes[0], panel_titles):
        plot = data.copy()
        plot["label"] = plot["scheme"].map(DISPLAY)
        colors = [PALETTE[str(s)] for s in plot["scheme"]]
        ax.bar(plot["label"], plot["seconds"], color=colors, width=0.68)
        apply_hatches(ax, list(plot["scheme"]))
        format_log_axis(ax)
        ax.set_title(title, pad=3)
        ax.set_ylabel("Time (s)")
        ax.tick_params(axis="x", rotation=32)
        for tick in ax.get_xticklabels():
            tick.set_ha("right")
        shift_xticklabels_right(ax)

    line_specs = [
        ("(d) Audit time vs. files", line_data["m"], "m", "Files"),
        ("(e) Verify time vs. challenges", line_data["c"], "c", "Challenges/file"),
        ("(f) Store time vs. file size", line_data["file"], "file_mb", "File size (MB)"),
    ]
    for ax, (title, data, x, xlabel) in zip(axes[1], line_specs):
        for scheme in SCHEME_ORDER:
            part = data[data["scheme"] == scheme].sort_values(x)
            if part.empty:
                continue
            ax.plot(
                part[x],
                part["seconds"],
                marker="o",
                markersize=2.7,
                label=DISPLAY[scheme],
                color=PALETTE[scheme],
            )
        format_log_axis(ax)
        ax.set_title(title, pad=3)
        ax.set_xlabel(xlabel)
        ax.set_ylabel("Time (s)")

    handles, labels = axes[1][0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        ncol=5,
        loc="upper center",
        bbox_to_anchor=(0.5, 1.025),
        frameon=False,
        columnspacing=1.0,
        handlelength=1.5,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.955), w_pad=0.8, h_pad=0.8)
    save_all(fig, "combined_cost_comparison")


def main() -> None:
    setup_style()

    main_df = load_csv("cost_model_main.csv")
    scenario = "100MB_m1000_c690_s100"
    one = main_df[main_df["scenario"] == scenario].copy()

    audit = one[one["phase"].isin(["proofgen", "verify"])].groupby("scheme", observed=True, as_index=False)["seconds"].sum()
    audit["scheme"] = pd.Categorical(audit["scheme"], categories=SCHEME_ORDER, ordered=True)
    audit = audit.sort_values("scheme")
    verify = one[one["phase"] == "verify"].copy().sort_values("scheme")
    store = one[one["phase"] == "store"].copy().sort_values("scheme")

    vary_m = load_csv("vary_m_audit.csv")
    vary_c = load_csv("vary_c_verify.csv")
    vary_file = load_csv("vary_file_store.csv")

    bar_figure(audit, "audit_time_100MB_paper", "Total audit cost", "Time (s, log)")
    bar_figure(verify, "verify_time_100MB_paper", "Verification cost", "Time (s, log)")
    bar_figure(store, "store_time_100MB_paper", "Store/TagGen cost", "Time (s, log)")
    line_figure(vary_m, "m", "vary_m_audit_paper", "Audit scaling with files", "Number of files m", "Time (s, log)")
    line_figure(vary_c, "c", "vary_c_verify_paper", "Verification scaling with challenges", "Challenge size c", "Time (s, log)")
    line_figure(vary_file, "file_mb", "vary_file_store_paper", "Store scaling with file size", "File size (MB)", "Time (s, log)")
    combined_panel(
        {"audit": audit, "verify": verify, "store": store},
        {"m": vary_m, "c": vary_c, "file": vary_file},
    )

    print(f"Wrote paper figures to {OUT}")


if __name__ == "__main__":
    main()
